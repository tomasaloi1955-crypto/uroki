def build_lesson(spec, next_topic):
    n = spec["n"]
    items = spec["items"]
    slides = []

    # Титульный слайд
    slides.append({
        "id": "01_title",
        "title": f'Урок {n} · {spec["topic"]}',
        "lines": [COURSE, f"Учитель: {TEACHER}"],
        "speech": [{"lang": "ru",
                    "text": f"Ассаляму алейкум, дорогие сёстры! С вами {TEACHER}, "
                            f"это урок номер {n}. Тема сегодня: {spec['topic']}. "
                            + spec["intro"]}],
    })

    # Контентные слайды: по 3 пункта на слайд
    chunk = 3
    for ci, start in enumerate(range(0, len(items), chunk), 1):
        part = items[start:start + chunk]
        lines = [f"{ar} — {tr} — {ru}" for ar, tr, ru in part]

        speech = []
        for k, (ar, tr, ru) in enumerate(part, start + 1):
            speech.append({"lang": "ru",
                           "text": f"Номер {k}: {ru}. Слушайте внимательно: "})
            speech.append({"lang": "ar", "text": ar + "."})
            speech.append({"lang": "ru", "text": f"{tr}. Слушаем ещё раз и запоминаем: "})
            speech.append({"lang": "ar", "text": ar + "."})
            speech.append({"lang": "ru",
                           "text": "А теперь скажите сами, вслух. Смелее. "
                                   "И проверим себя: "})
            speech.append({"lang": "ar", "text": ar + "."})
        speech.append({"lang": "ru",
                       "text": "Отлично. Прежде чем идти дальше, пробегитесь глазами "
                               "по экрану и повторите каждую строку ещё раз."})

        slides.append({
            "id": f"{ci + 1:02d}_part{ci}",
            "title": spec["topic"],
            "lines": lines,
            "speech": speech,
        })

    # Повторение всех слов урока
    recap_speech = [{"lang": "ru",
                     "text": "А теперь — самое полезное: повторим весь урок целиком. "
                             "Я называю по-русски, потом звучит арабский — "
                             "повторяйте вслух за диктором."}]
    for ar, tr, ru in items:
        recap_speech.append({"lang": "ru", "text": f"{ru}: "})
        recap_speech.append({"lang": "ar", "text": ar + "."})
    recap_speech.append({"lang": "ru",
                         "text": "Машаллах! Вы повторили все слова сегодняшнего урока."})
    slides.append({
        "id": f"{len(slides) + 1:02d}_recap",
        "title": "Повторим всё",
        "lines": [f"{ar} — {tr}" for ar, tr, _ in items],
        "body_size": 30 if len(items) <= 6 else 26,
        "speech": recap_speech,
    })

    # Задание
    slides.append({
        "id": f"{len(slides) + 1:02d}_task",
        "title": "Задание",
        "lines": [
            "1. Повтори все слова урока вслух",
            "2. Запиши голосовое с любыми тремя",
            "Жду тебя в комментариях!",
        ],
        "speech": [{"lang": "ru",
                    "text": "Ваше задание. Повторите все сегодняшние слова вслух три раза. "
                            "Затем запишите голосовое сообщение в комментариях: произнесите "
                            "любые три слова или фразы из урока. Я слушаю каждую из вас. "
                            "Не бойтесь ошибаться — ошибки это ступеньки к знанию."}],
    })

    # Финал
    slides.append({
        "id": f"{len(slides) + 1:02d}_end",
        "title": "До встречи!",
        "lines": [
            "Повтори урок вечером ещё раз",
            f"Завтра — Урок {n + 1}" + (f": {next_topic}" if next_topic else ""),
            "Подпишись, чтобы не пропустить",
        ],
        "speech": [{"lang": "ru",
                    "text": "На этом урок завершён, машаллах, вы отлично поработали! "
                            "Вечером откройте урок ещё раз и повторите слова. "
                            + (f"Завтра нас ждёт урок на тему: {next_topic}. " if next_topic else "")
                            + f"Подпишитесь на канал, чтобы не пропустить. С вами была {TEACHER}. "},
                   {"lang": "ar", "text": "مَعَ السَّلَامَة!"},
                   {"lang": "ru", "text": "До встречи, дорогие!"}],
    })

    return {
        "course": COURSE,
        "lesson_number": n,
        "topic": spec["topic"],
        "teacher": TEACHER,
        "voice_ru": VOICE_RU,
        "voice_ar": VOICE_AR,
        "body_size": 40,
        "slides": slides,
    }


def main():
    for i, spec in enumerate(CURRICULUM):
        next_topic = CURRICULUM[i + 1]["topic"] if i + 1 < len(CURRICULUM) else None
        lesson = build_lesson(spec, next_topic)
        out = Path(f'arabic_{spec["n"]:03d}.json')
        out.write_text(json.dumps(lesson, ensure_ascii=False, indent=2),
                       encoding="utf-8")
        print(f"{out}  ({spec['topic']})")
    print(f"\nГотово: {len(CURRICULUM)} уроков. Дальше: python make_all.py")


if __name__ == "__main__":
    main()
