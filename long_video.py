def elevenlabs_tts_slow(text: str, out_mp3: Path):
    """Как shorts_v2.elevenlabs_tts, но чуть медленнее (speed=0.85) —
    длинное учебное видео легче слушать в спокойном темпе, и это же
    честно добавляет хронометража без искусственного раздувания текста.

    С повторами: на 19 сценах транзитный сетевой таймаут ElevenLabs
    иначе роняет всю сборку и теряет прогресс по текущей сцене."""
    key = os.environ["ELEVENLABS_API_KEY"]
    voice = os.environ["ELEVENLABS_VOICE_ID"]
    req_body = json.dumps({"text": text,
                           "model_id": "eleven_multilingual_v2",
                           "voice_settings": {"stability": 0.6,
                                              "similarity_boost": 0.75,
                                              "speed": 0.85}}).encode()
    last_err = None
    for attempt in range(4):
        try:
            req = urllib.request.Request(
                f"https://api.elevenlabs.io/v1/text-to-speech/{voice}"
                "?output_format=mp3_44100_128",
                data=req_body,
                headers={"xi-api-key": key, "Content-Type": "application/json"},
            )
            with urllib.request.urlopen(req, timeout=120) as r:
                out_mp3.write_bytes(r.read())
            return
        except Exception as e:
            last_err = e
            print(f"    озвучка: попытка {attempt + 1} не удалась ({e}), "
                  f"жду и пробую снова...")
            time.sleep(10)
    raise last_err


# Служебные частицы, которые повторяются из урока в урок и не всегда
# попадают в lines/ar_big/bullets в чистом виде для авторазбора.
SEED_AR_VOCAB = {"ма": "ما", "хал": "هل", "наам": "نعم", "ля": "لا"}


def build_ar_vocab(scenes):
    """Собирает словарь транслит-слово -> арабское написание из lines/
    ar_big/bullets всего эпизода (там уже есть верные пары "как
    произносится" <-> "как пишется" для слов, которые проходят в
    уроке)."""
    vocab = dict(SEED_AR_VOCAB)

    def add_pair(ar_phrase, ru_phrase):
        ar_words = ar_phrase.replace("؟", "").replace("?", "").split()
        # strip_accents(): ключи должны совпадать со словами уже после
        # той же нормализации, что применяется к тексту озвучки (иначе
        # "бейт" не найдёт "беит" после вычитания диакритики из "й").
        ru_words = strip_accents(ru_phrase).split("—")[0].strip().split()
        if len(ar_words) != len(ru_words):
            return
        for aw, rw in zip(ar_words, ru_words):
            key = rw.strip(",.!?").lower()
            if key and key not in vocab:
                vocab[key] = aw

    for sc in scenes:
        if sc.get("ar_big") and sc.get("sub"):
            add_pair(sc["ar_big"], sc["sub"])
        for ar, ru in sc.get("lines", []):
            add_pair(ar, ru)
        for ar, ru in sc.get("bullets", []):
            add_pair(ar, ru)
    return vocab


def split_vocab_occurrences(text, vocab):
    """Режет текст на чередующиеся сегменты [("ru", кусок), ("ar", слово)]
    по каждому словарному слову (границы слова, без учёта регистра) —
    как split_word_occurrences в shorts_v2.py, но сразу для НЕСКОЛЬКИХ
    разных арабских слов (в сцене длинного видео их обычно не одно).

    Кусок из одних знаков препинания (арабское слово сразу после запятой
    или в конце предложения — частый случай при перечислении числительных)
    в TTS не отправляем: голый "." или "," ElevenLabs озвучивает
    посторонним звуком, а пауза между сегментами и так есть (тишина в
    synthesize_plan_slow)."""
    if not vocab or not text.strip():
        return [("ru", text)] if text.strip() else []
    pattern = re.compile(
        r"\b(" + "|".join(re.escape(w) for w in
                          sorted(vocab, key=len, reverse=True)) + r")\b",
        re.IGNORECASE)
    segs = []
    pos = 0
    for m in pattern.finditer(text):
        chunk = text[pos:m.start()]
        if re.search(r"\w", chunk, re.UNICODE):
            segs.append(("ru", chunk))
        segs.append(("ar", vocab[m.group(0).lower()]))
        pos = m.end()
    tail = text[pos:]
    if re.search(r"\w", tail, re.UNICODE):
        segs.append(("ru", tail))
    return segs


# Чем озвучивается текущая серия; решает build_episode по остатку
# бесплатного лимита ElevenLabs (см. voice_budget.py).
USE_ELEVEN = False


def episode_chars(scenes, vocab):
    """Сколько символов ElevenLabs уйдёт на серию (повторы кэшируются)."""
    seen = set()
    for sc in scenes:
        for kind, text in split_vocab_occurrences(strip_accents(sc["speech"]), vocab):
            seen.add((kind, text))
    return sum(len(t) for _, t in seen)


def synthesize_plan_slow(plan, out_mp3: Path, work: Path):
    """Синтезирует план [("ru"|"ar", текст)] по сегментам и склеивает их
    через ffmpeg — вместо одного запроса на всю реплику сцены целиком.
    Так и арабские слова звучат одинаково чисто на каждом повторе (без
    "плывущего" произношения ElevenLabs при повторах внутри одной
    генерации), и русская речь не торопится/не наезжает сама на себя —
    что случалось, когда модели приходилось на лету переключаться между
    транслитом и арабской вязью посреди одного предложения.

    Кэш сегментов — по хэшу текста, а не по порядковому номеру: разные
    сцены одного эпизода делят один work/, и одно и то же слово может
    встретиться в нескольких сценах — тогда оно синтезируется единожды
    на весь эпизод."""
    if not plan:
        plan = [("ru", "")]
    clips = []
    silence = work / "_silence.mp3"
    if not silence.exists():
        ffmpeg("-f", "lavfi", "-i", "anullsrc=r=44100:cl=mono",
               "-t", "0.35", "-q:a", "9", str(silence))
    for kind, text in plan:
        # движок в ключе кэша: при смене голоса старые клипы не подмешаются
        key = hashlib.md5(f"{USE_ELEVEN}:{kind}:{text}".encode("utf-8")).hexdigest()[:12]
        clip = work / f"_seg_{key}.mp3"
        if not clip.exists():
            if USE_ELEVEN:
                elevenlabs_tts_slow(text, clip)
            else:
                free_tts(kind, text, clip, ru_rate="-10%")
        clips.append(clip)
        clips.append(silence)

    cmd = []
    for c in clips:
        cmd += ["-i", str(c)]
    n = len(clips)
    filt = "".join(f"[{i}:a]" for i in range(n)) + f"concat=n={n}:v=0:a=1[out]"
    ffmpeg(*cmd, "-filter_complex", filt, "-map", "[out]", str(out_mp3))


