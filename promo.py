# -*- coding: utf-8 -*-
"""
Реклама курса «Алфавит + таджвид» во всех автопубликациях арабского канала.

Ссылка на курс — COURSE_URL ниже или переменная окружения COURSE_URL
(секрет/переменная GitHub). Пока ссылки нет, реклама НИГДЕ не появляется:
лучше без рекламы, чем «ссылка в описании», которой там нет.

Где показывается:
  - описание каждого ролика: блок с курсом — первыми строками (их YouTube
    показывает без «ещё»);
  - шортсы слов (shorts_v2.py): в нечётных роликах плашка внизу и голос
    зовут на курс, в чётных — как раньше, «подпишись». Так реклама идёт
    через день и не надоедает.
"""

import os

# Ссылки Tribute, например https://t.me/tribute/app?startapp=...
COURSE_URL = "https://web.tribute.tg/s/18rW"  # тариф «Самостоятельно» (или общая)
CHECK_URL = "https://web.tribute.tg/s/18VF"  # тариф «С проверкой ДЗ»; пусто — ведёт на COURSE_URL

# Плашка внизу кадра шортса (коротко: на экране максимум 2 строки)
# В Shorts ссылки в описании НЕ кликаются (так YouTube борется со спамом),
# поэтому зовём в шапку канала — там ссылки кликаются
SCREEN_TEXT = "Курс: алфавит + таджвид — ссылка в шапке канала"

# Голосом в конце шортса (ElevenLabs, русская фраза)
VOICE_TEXT = ("Хочешь читать Коран правильно? "
              "Мой курс по алфавиту и таджвиду — ссылка в шапке канала.")


def course_url() -> str:
    return (os.environ.get("COURSE_URL") or COURSE_URL).strip()


def check_url() -> str:
    return (os.environ.get("CHECK_URL") or CHECK_URL).strip()


def enabled() -> bool:
    return bool(course_url())


def course_day(n: int) -> bool:
    """Шортс n рекламирует курс (иначе — обычное «подпишись»)."""
    return enabled() and n % 2 == 1


def description_block() -> str:
    """Блок для начала описания; пустая строка, если ссылки нет."""
    if not enabled():
        return ""
    return ("📖 Научись читать Коран с нуля: курс «Алфавит + таджвид» "
            "по книге «Муаллим сани»\n"
            "Ссылки кликаются в шапке канала, а здесь их можно скопировать:\n"
            + tariffs() + "\n")


def tariffs() -> str:
    if check_url():  # у каждого тарифа своя ссылка
        return ("✅ Самостоятельно — видеоуроки и материалы\n"
                f"👉 {course_url()}\n"
                "✅ С проверкой ДЗ — присылаешь чтение, я исправляю каждую ошибку\n"
                f"👉 {check_url()}\n")
    return (f"👉 {course_url()}\n"
            "✅ Самостоятельно — видеоуроки и материалы\n"
            "✅ С проверкой ДЗ — присылаешь чтение, я исправляю каждую ошибку\n")


def social_line() -> str:
    """Для Instagram и TikTok: ссылки в подписи там не кликаются,
    поэтому зовём в шапку профиля (туда ставится ссылка на курс)."""
    if not enabled():
        return ""
    return ("📖 Курс «Алфавит + таджвид» — самостоятельно или с проверкой ДЗ. "
            "Ссылка в шапке профиля")


def with_ad(description: str) -> str:
    return description_block() + description
